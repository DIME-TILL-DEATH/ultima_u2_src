void note_tun(void)
{
	for(uint8_t i = 0 ; i < 2 ; i++)
	{
		sh1106_gotoXY(74,i + 1);
		for(uint8_t f = 0; f < 13 ; f++)zero_buf[f];//ErOled_send_data(0);
		spi3_dma_init_transfer(13,(uint32_t*)zero_buf);
	}
	for(uint8_t i = 0 ; i < 2 ; i++)
	{
		sh1106_gotoXY(56,i + 1);
		extern float c3;
		if(c3)for(uint8_t f = 0; f < 15 ; f++)font_buf[f] = not_tun[f*2 + i + not_ind[t_no]*30];
		else for(uint8_t f = 0; f < 15 ; f++)font_buf[f] = tire[f*2 + i];
		spi3_dma_init_transfer(15,(uint32_t*)font_buf);
	}
	if((t_no == 1) || (t_no == 3) || (t_no == 6) || (t_no == 8) || (t_no == 10))diez_tun();
}

const uint8_t strelk_tun[] = {0x80, 0xC0, 0xE0, 0xF0, 0xF8, 0xFC, 0xFE, 0xFF, 0xFE, 0xFC, 0xF8, 0xF0, 0xE0, 0xC0, 0x80};

void strel_tun(void)
{
	if(t_po1 != t_po)
	{
		sh1106_gotoXY(t_po1 - 8,4);
		for(uint8_t i = 0 ; i < 15 ; i++)zero_buf[i];
		spi3_dma_init_transfer(15,(uint32_t*)zero_buf);
	}
	if(t_po1 < t_po)
	{
		if((t_po - t_po1) > 50)t_po1 += 20;
		else {
			if((t_po - t_po1) > 30)t_po1 += 10;
			else  {
				if((t_po - t_po1) > 20)t_po1 += 5;
				else {
					if((t_po - t_po1) > 10)t_po1 += 3;
					else {
						if((t_po - t_po1) > 5)t_po1 += 2;
						else t_po1++;
					}
				}
			}
		}
	}
	if(t_po1 > t_po)
	{
		if((t_po1 - t_po) > 50)t_po1 -= 20;
		else {
			if((t_po1 - t_po) > 30)t_po1 -= 10;
			else  {
				if((t_po1 - t_po) > 20)t_po1 -= 5;
				else {
					if((t_po1 - t_po) > 10)t_po1 -= 3;
					else {
						if((t_po1 - t_po) > 5)t_po1 -= 2;
						else t_po1--;
					}
				}
			}
		}
	}
	//t_po1 = t_po;
	if((t_po1 >= 62) && (t_po1 <= 66))
	{
		Arsys_sym(7,1,62,0);
		Arsys_sym(115,1,60,0);
		switch (t_po1){
		case 62:Arsys_sym(13,1,62,0);Arsys_sym(19,1,62,0);Arsys_sym(103,1,60,3);Arsys_sym(109,1,60,3);break;
		case 63:Arsys_sym(13,1,62,0);Arsys_sym(19,1,62,0);Arsys_sym(103,1,60,3);Arsys_sym(109,1,60,0);break;
		case 64:Arsys_sym(13,1,62,0);Arsys_sym(19,1,62,0);Arsys_sym(103,1,60,0);Arsys_sym(109,1,60,0);break;
		case 65:Arsys_sym(13,1,62,0);Arsys_sym(19,1,62,3);Arsys_sym(103,1,60,0);Arsys_sym(109,1,60,0);break;
		case 66:Arsys_sym(13,1,62,3);Arsys_sym(19,1,62,3);Arsys_sym(103,1,60,0);Arsys_sym(109,1,60,0);break;
		}
	}
	else {
		Arsys_sym(7,1,62,3);
		Arsys_sym(13,1,62,3);
		Arsys_sym(19,1,62,3);
		Arsys_sym(115,1,60,3);
		Arsys_sym(109,1,60,3);
		Arsys_sym(103,1,60,3);
	}
	sh1106_gotoXY(t_po1 - 8,4);
	for(uint8_t i = 0 ; i < 15 ; i++)font_buf[i] = strelk_tun[i];
	spi3_dma_init_transfer(15,(uint32_t*)font_buf);
	note_tun();
}
