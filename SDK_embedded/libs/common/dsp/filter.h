template <typename T, typename V> class alfa_filter_t
{
  public:
    alfa_filter_t (): y(0) {}

    void tau( const V Ts , const V t )
    {
      a1 = Ts / t ;
      a0 = 1.0 - a1 ;
    }

    V tau( const V Ts)
    {
      return Ts / a1 ;
    }

    const T& update ( const T& x )
    {
      y = a0*y + a1*x ;
      return y ;
    }

    V a0 ;  // alfa
    V a1 ;  // 1 - alfa
    T y ; // выход фильтра
} ;

