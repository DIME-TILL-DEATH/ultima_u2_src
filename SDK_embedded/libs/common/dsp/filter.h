template <typename T> class irr_second_order_filter_t
{
   public:

   typedef struct
   {
     T b0_a0 ;
     T b1_a0 ;
     T b2_a0 ;
     T a1_a0 ;
     T a2_a0 ;

     inline void reset() { b0_a0=b1_a0=b2_a0=a1_a0=a2_a0=0; }
   }
   k_t ;

   irr_second_order_filter_t() { k.reset(); }

   inline const T& update ( const T& x )
     {
       y[2]=y[1] ; y[1] = y[0] ;
       x[2]=x[1] ; x[1] = x[0] ;  x[0] = x ;
       y[0] = k.b0_a0*x[0] + k.b1_a0*x[1] + k.b2_a0*x[2] - k.a1_a0*y[1] - k.a2_a0*y[2] ;
       return y[0] ;
     }

   inline void reset()
     {
       x[0]=x[1]=x[2]=y[0]=y[1]=y[2]=0;
       k.reset();
     }

   inline void set(const k_t& k )
     {
       this->k = k ;
     }

   private:
     T y[3] ;
     T x[3] ;

     k_t k ;
};
